const GENERIC_NEXT = "查看提示后修改标的、价格或数量再试。若涉及额度，先到「资源」申请个人额度。";

export function hasOperationGuidance(message: string): boolean {
	return message.includes("下一步：");
}

export function explainOperationFailure(raw: string | null | undefined, fallback = "操作未成功"): string {
	const message = (raw ?? "").trim() || fallback;
	if (hasOperationGuidance(message)) return message;
	const rule = GUIDANCE_RULES.find((item) => message.includes(item.match));
	return `${message}${NEXT_STEP_MARKER}${rule?.next ?? GENERIC_NEXT}`;
}

export function splitOperationGuidance(raw: string): { reason: string; next: string } {
	const explained = explainOperationFailure(raw);
	const index = explained.indexOf(NEXT_STEP_MARKER);
	if (index >= 0) {
		return {
			reason: explained.slice(0, index),
			next: explained.slice(index + NEXT_STEP_MARKER.length),
		};
	}
	return { reason: explained, next: GENERIC_NEXT };
}
