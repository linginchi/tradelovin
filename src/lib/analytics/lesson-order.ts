/**
 * 从视频标题中提取中文课程序号，支持客户端和服务端共同使用。
 * "第一课" → 1, "第二课" → 2, ..., 无法识别则返回 999
 */
export function extractLessonOrder(title: string): number {
  const m = title.match(/第([一二三四五六七八九十百零]+)课/);
  if (!m) return 999;
  const cn = m[1] ?? "";
  const map: Record<string, number> = {
    "一": 1, "二": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9, "十": 10,
    "十一": 11, "十二": 12, "十三": 13, "十四": 14, "十五": 15,
    "十六": 16, "十七": 17, "十八": 18, "十九": 19, "二十": 20,
    "零": 0,
  };
  return map[cn] ?? 999;
}
